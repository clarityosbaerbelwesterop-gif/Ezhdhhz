"""Calibration text for donor analysis: chunks of human-written text that fit one seed window.

Every chunk ends on a line boundary and has at most ``max_seed_tokens`` seed tokens, so the seed model
can read it as one window from position 0 and a donor reads the same bytes with its own tokenizer.
Chunks carry their source, byte range and SHA-256; nothing is generated by a model.
"""
from __future__ import annotations

import hashlib
from pathlib import Path


def chunk_text(text: str, seed, max_seed_tokens: int = 512, min_bytes: int = 700, max_chunks: int = 3,
               skip_lines: int = 0) -> list[tuple[int, int, str]]:
    """Consecutive line-aligned chunks [(byte_start, byte_end, text)] with <= max_seed_tokens seed tokens."""
    lines = text.splitlines(keepends=True)[skip_lines:]
    start = len("".join(text.splitlines(keepends=True)[:skip_lines]).encode())
    out, cur, cur_tok = [], [], 0
    off = start
    for ln in lines:
        n = len(seed.encode(ln))
        if n > max_seed_tokens:                       # a single over-long line ends the current chunk
            cur, cur_tok = [], 0
            off += len(ln.encode())
            start = off
            continue
        if cur_tok + n > max_seed_tokens:
            body = "".join(cur)
            if len(body.encode()) >= min_bytes:
                out.append((start, start + len(body.encode()), body))
                if len(out) >= max_chunks:
                    return out
            start += len(body.encode())
            cur, cur_tok = [], 0
        cur.append(ln)
        cur_tok += n
        off += len(ln.encode())
    return out


def build(sources: list[dict], seed, max_seed_tokens: int = 512, per_source: int = 3) -> list[dict]:
    """sources: [{"domain", "name", "text" | "path", "skip_lines"?, "license"}] -> chunk records."""
    chunks = []
    for s in sources:
        text = s["text"] if "text" in s else Path(s["path"]).read_text(encoding="utf-8", errors="replace")
        for a, b, body in chunk_text(text, seed, max_seed_tokens, max_chunks=s.get("chunks", per_source),
                                     skip_lines=s.get("skip_lines", 0)):
            ids = seed.encode(body)
            assert len(ids) <= max_seed_tokens and seed.decode_bytes(ids) == body.encode()
            chunks.append({"domain": s["domain"], "source": s["name"], "license": s.get("license", ""),
                           "byte_range": [a, b], "bytes": b - a, "seed_tokens": len(ids),
                           "sha256": hashlib.sha256(body.encode()).hexdigest(), "text": body})
    for i, c in enumerate(chunks):
        c["id"] = i
    return chunks


def python_stdlib_sources(stdlib: str, code_files: list[str], topics: list[str], c_headers: list[str] = ()) -> list[dict]:
    """Code = CPython standard-library modules (+ C headers); prose = the Python language reference
    as shipped in pydoc_data.topics. Both are human-written; PSF license (glibc headers: LGPL)."""
    import importlib
    out = []
    for f in code_files:
        out.append({"domain": "code", "name": f"cpython:{f}", "path": f"{stdlib}/{f}", "skip_lines": 40,
                    "license": "PSF-2.0"})
    for h in c_headers:
        out.append({"domain": "code", "name": f"glibc:{h}", "path": f"/usr/include/{h}", "skip_lines": 30,
                    "license": "LGPL-2.1+", "chunks": 1})
    T = importlib.import_module("pydoc_data.topics").topics
    for t in topics:
        out.append({"domain": "prose", "name": f"python-reference:{t}", "text": T[t], "license": "PSF-2.0",
                    "chunks": 2})
    return out
