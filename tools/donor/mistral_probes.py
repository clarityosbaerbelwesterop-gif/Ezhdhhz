#!/usr/bin/env python3
"""Probe set for locating reasoning / adaptive-thinking / in-context-learning experts in Mistral Large 4.

All natural-language content is human-written and licensed (GSM8K: MIT; WikiText-2: CC-BY-SA; CPython
standard library: PSF). The few-shot rule tasks are generated by this program from a seeded RNG (random
letter strings and deterministic rules); no model output is used anywhere.

Every token gets labels:  kind (wiki | code | gsm_raw | chat | icl), seg (control | question | reasoning |
answer | icl_input | icl_output), effort (0 n/a, 1 low, 2 medium, 3 high), think (chat: 1 = with a
[THINK] block), item, shot, half (item parity, for split-half stability).
"""
import argparse
import json
import random
import re

KINDS = ["wiki", "code", "gsm_raw", "chat", "icl"]
SEGS = ["control", "question", "reasoning", "answer", "icl_input", "icl_output", "text"]
EFFORTS = ["", "low", "medium", "high"]


def clean_solution(ans: str) -> tuple[str, str]:
    steps, final = ans.split("####")
    return re.sub(r"<<[^>]*>>", "", steps).strip(), final.strip()


def label_spans(text: str, offsets, spans: list[tuple[int, int, int]], default: int) -> list[int]:
    """spans: (char_start, char_end, seg). A token gets the seg of the span containing its first char."""
    out = []
    for a, b in offsets:
        seg = default
        for s, e, g in spans:
            if s <= a < e and b > a:
                seg = g
                break
        out.append(seg)
    return out


def icl_tasks():
    return {
        "reverse": lambda s: s[::-1],
        "upper": lambda s: s.upper(),
        "double": lambda s: s + s,
        "shift1": lambda s: "".join(chr((ord(c) - 97 + 1) % 26 + 97) for c in s),
        "sort": lambda s: "".join(sorted(s)),
        "ends": lambda s: s[0] + s[-1],
        "length": lambda s: str(len(s)),
        "last3": lambda s: s[-3:],
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tokenizer-dir", required=True)
    ap.add_argument("--gsm8k", required=True)
    ap.add_argument("--wikitext", required=True)
    ap.add_argument("--code-chunks", required=True, help="calibration chunks JSON (code domain reused)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--n-gsm-raw", type=int, default=28)
    ap.add_argument("--n-chat", type=int, default=14)
    ap.add_argument("--n-wiki", type=int, default=14)
    ap.add_argument("--n-code", type=int, default=12)
    ap.add_argument("--shots", type=int, default=10)
    ap.add_argument("--icl-instances", type=int, default=2)
    a = ap.parse_args()
    import pyarrow.parquet as pq
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(a.tokenizer_dir)
    bos = tok.bos_token_id
    seqs = []

    def add(text, kind, spans, default, item, effort=0, think=0, shot_spans=None, add_bos=True):
        enc = tok(text, add_special_tokens=False, return_offsets_mapping=True)
        ids, offs = enc["input_ids"], enc["offset_mapping"]
        seg = label_spans(text, offs, spans, default)
        shot = [0] * len(ids)
        if shot_spans:
            for i, (x, y) in enumerate(offs):
                for s, e, k in shot_spans:
                    if s <= x < e:
                        shot[i] = k
        if add_bos and (not ids or ids[0] != bos):
            ids, seg, shot = [bos] + ids, [0] + seg, [0] + shot
        seqs.append({"kind": KINDS.index(kind), "item": item, "effort": effort, "think": think, "half": item % 2,
                     "ids": ids, "seg": seg, "shot": shot, "chars": len(text)})

    T = SEGS.index("text")
    # ---- wiki prose: paragraphs of at least 600 characters
    paras = [r["text"].strip() for r in pq.read_table(a.wikitext).to_pylist() if len(r["text"].strip()) >= 600]
    for i, p in enumerate(paras[:a.n_wiki]):
        add(p[:1600], "wiki", [], T, i)
    # ---- code
    code = [c for c in json.load(open(a.code_chunks)) if c["domain"] == "code"]
    for i, c in enumerate(code[:a.n_code]):
        add(c["text"], "code", [], T, i)
    # ---- GSM8K raw: question + worked solution as plain text
    g = pq.read_table(a.gsm8k).to_pylist()
    Q, R, A_ = SEGS.index("question"), SEGS.index("reasoning"), SEGS.index("answer")
    for i, r in enumerate(g[:a.n_gsm_raw]):
        steps, final = clean_solution(r["answer"])
        text = f"{r['question']}\n{steps}\nThe answer is {final}."
        q_end = len(r["question"]) + 1
        s_end = q_end + len(steps) + 1
        add(text, "gsm_raw", [(0, q_end, Q), (q_end, s_end, R), (s_end, len(text), A_)], T, i)
    # ---- chat format: the same problem under three reasoning efforts, with and without a thinking block
    for i, r in enumerate(g[a.n_gsm_raw:a.n_gsm_raw + a.n_chat]):
        steps, final = clean_solution(r["answer"])
        ans = f"The answer is {final}."
        for think in (1, 0):
            for e in (1, 2, 3):
                content = [{"type": "thinking", "thinking": steps}, {"type": "text", "text": ans}] if think else ans
                text = tok.apply_chat_template([{"role": "user", "content": r["question"]},
                                                {"role": "assistant", "content": content}],
                                               tokenize=False, reasoning_effort=EFFORTS[e])
                spans = []
                qa = text.find(r["question"])
                spans.append((qa, qa + len(r["question"]), Q))
                if think:
                    sa = text.find(steps, qa + len(r["question"]))
                    spans.append((sa, sa + len(steps), R))
                aa = text.rfind(ans)
                spans.append((aa, aa + len(ans), A_))
                add(text, "chat", spans, 0, i, effort=e, think=think, add_bos=False)
    # ---- in-context learning: k demonstrations of a hidden rule on random strings
    rng = random.Random(20261110)
    I, O = SEGS.index("icl_input"), SEGS.index("icl_output")
    item = 0
    for name, fn in icl_tasks().items():
        for _ in range(a.icl_instances):
            text, spans, shots = "", [], []
            for k in range(a.shots):
                s = "".join(rng.choice("abcdefghijklmnopqrstuvwxyz") for _ in range(rng.randint(5, 8)))
                head = f"Input: {s}\nOutput: "
                out = fn(s)
                spans.append((len(text), len(text) + len(head), I))
                spans.append((len(text) + len(head), len(text) + len(head) + len(out), O))
                shots.append((len(text), len(text) + len(head) + len(out) + 2, k + 1))
                text += head + out + "\n\n"
            add(text, "icl", spans, I, item, shot_spans=shots)
            seqs[-1]["task"] = name
            item += 1
    n = sum(len(s["ids"]) for s in seqs)
    by = {}
    for s in seqs:
        by[KINDS[s["kind"]]] = by.get(KINDS[s["kind"]], 0) + len(s["ids"])
    meta = {"kinds": KINDS, "segs": SEGS, "efforts": EFFORTS, "sequences": len(seqs), "tokens": n, "tokens_by_kind": by,
            "max_len": max(len(s["ids"]) for s in seqs),
            "sources": {"gsm8k": "openai/gsm8k@740312add88f781978c0658806c59bc2815b9866 main/test (MIT)",
                        "wikitext": "Salesforce/wikitext@b08601e04326c79dfdd32d625aee71d232d685c3 wikitext-2-raw-v1/test (CC-BY-SA-3.0)",
                        "code": "CPython 3.13 standard library (PSF-2.0)", "icl": "generated by this script, seed 20261110"}}
    json.dump({"meta": meta, "seqs": seqs}, open(a.out, "w"))
    print(json.dumps(meta, indent=1))
    ex = next(s for s in seqs if s["kind"] == 3 and s["think"] == 1 and s["effort"] == 3)
    print(repr(tok.decode(ex["ids"])[:420]))
    print([(tok.decode([t]), SEGS[g_]) for t, g_ in list(zip(ex["ids"], ex["seg"]))[:14]])


if __name__ == "__main__":
    main()
